def H(open_: str, close: str, closed: tuple[int, ...] = (), second: tuple[str, str] | None = None) -> dict:
    """Weekly hours helper. Days: 0=Mon..6=Sun."""
    ranges = [{"open": open_, "close": close}]
    if second:
        ranges.append({"open": second[0], "close": second[1]})
    return {d: ([] if d in closed else ranges) for d in range(7)}


